-- 세션마다 유지 기간을 따로 들고 있게 한다.
--
-- 지금까지는 누구든 로그인하면 이레 동안 그대로 유지됐다. 활동과 상관없이
-- 절대 기간이라, 집에서 로그인하고 다음 날 회사에서 열어도 그대로 들어가진다.
-- 관리자 계정도 마찬가지여서 공용 PC 에 열어 두면 그대로 남는다.
--
-- 갈래를 나눈다.
--   관리자     8시간   — 회원 개인정보와 모든 글을 볼 수 있어 짧게 둔다
--   회원      24시간
--   로그인 유지 14일    — 개인 기기에서 본인이 고른 경우만
-- 쓰는 동안에는 남은 시간이 절반 아래로 내려갈 때 다시 채운다(session.ts).
-- 그래서 계속 쓰는 사람은 끊기지 않고, 안 쓰면 알아서 만료된다.

ALTER TABLE sessions ADD COLUMN max_age_sec INTEGER NOT NULL DEFAULT 86400;

-- 이미 열려 있는 세션은 새 기준으로 다시 재운다. 이레짜리를 그대로 두면
-- 기간을 줄인 뜻이 없다.
UPDATE sessions SET max_age_sec = 86400;
DELETE FROM sessions;
