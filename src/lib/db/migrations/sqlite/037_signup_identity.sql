-- 한 사람이 계정을 여러 개 만들지 못하게 막는다.
--
-- 이메일은 얼마든지 새로 만들 수 있어 중복을 막는 열쇠가 되지 못한다.
-- 휴대전화번호를 필수로 받고 한 번호에 한 계정만 둔다. 번호의 주인인지까지는
-- 확인하지 못하므로(그건 문자 인증의 몫), 승인 화면의 중복 의심 표시가 함께 받친다.
--
-- 번호는 숫자만 남긴 꼴로 저장한다(lib/phone.ts). 모양이 다르다고 다른 번호로
-- 세면 중복을 막는 뜻이 없어진다.
--
-- 이미 있는 계정은 번호가 비어 있다. UNIQUE 는 빈 값(NULL)을 여럿 허용하므로
-- 옛 계정이 걸리지 않는다. 마이그레이션이 실패하면 ready() 가 모든 요청에서 터져
-- 사이트 전체가 500 이 되므로, 걸릴 일이 없는 것을 확인하고 넣는다.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_phone ON users(phone);

-- 회원사를 식별하는 값. 회사명은 적는 사람마다 달라지지만 이 번호는 하나로 정해진다.
-- 선택 항목이라 비어 있을 수 있고, 한 회사에 담당자가 여럿일 수 있으므로 UNIQUE 는 아니다.
ALTER TABLE users ADD COLUMN biz_number TEXT;
